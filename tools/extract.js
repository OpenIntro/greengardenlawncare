import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { unpack } from "./unpack.js";
import { buildFontCss } from "./fonts.js";
import { convertTemplate, fontLinkPartial, splitChrome } from "./convert.js";
import { bindSiteFacts } from "./bind-facts.js";
import { writeIfChanged } from "./write.js";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FULL_PAGE_CSS = "html,body{height:100%;margin:0}#dc-root,#dc-root>.sc-host{height:100%}\n";

function assetModule(assets) {
  const records = {};
  for (const asset of assets) {
    records[asset.key] = {
      src: asset.src,
      mime: asset.mime,
      alt: asset.alt,
      bytes: asset.bytes.length,
    };
  }
  return `// Generated by npm run extract. Do not edit by hand.\nexport default ${JSON.stringify(records, null, 2)};\n`;
}

export function extractProject({ root = projectRoot, html } = {}) {
  const source = html ?? fs.readFileSync(path.join(root, "index.html"), "utf8");
  const bundle = unpack(source);
  const build = path.join(root, "build");
  writeIfChanged(path.join(build, "template.html"), bundle.template);
  writeIfChanged(path.join(build, "page-order.json"), `${JSON.stringify(bundle.views, null, 2)}\n`);
  if (bundle.logic) writeIfChanged(path.join(build, "logic.js"), bundle.logic);

  for (const asset of bundle.assets) {
    const folder = asset.mime === "font/woff2" ? "fonts" : "img";
    writeIfChanged(path.join(build, "assets", folder, asset.filename), asset.bytes);
    writeIfChanged(path.join(root, "src", "assets", folder, asset.filename), asset.bytes);
  }
  writeIfChanged(path.join(root, "src", "_data", "assets.js"), assetModule(bundle.assets));

  const converted = convertTemplate(bundle.template, { uriToSrc: bundle.uriToSrc });
  const bound = bindSiteFacts(converted.html);
  const parts = splitChrome(bound);
  writeIfChanged(path.join(build, "chrome", "header.njk"), parts.header);
  writeIfChanged(path.join(build, "chrome", "primary-nav.njk"), parts.nav);
  writeIfChanged(path.join(build, "chrome", "footer.njk"), parts.footer);
  writeIfChanged(path.join(build, "chrome", "bottom-bar.njk"), parts.bottom);
  writeIfChanged(path.join(build, "views", `${bundle.views[0]}.njk`), parts.view);
  writeIfChanged(path.join(build, "css", "hover.css"), converted.hoverCss);

  const helmet = converted.helmet;
  if (!helmet) throw new Error("Design template is missing <helmet>");
  const fontPaths = new Map();
  for (const asset of bundle.assets) {
    if (asset.mime !== "font/woff2") continue;
    for (const [uri, src] of bundle.uriToSrc) {
      if (src === asset.src) fontPaths.set(uri, src);
    }
  }
  writeIfChanged(path.join(root, "src", "assets", "css", "fonts.css"), buildFontCss(helmet.style, fontPaths));
  writeIfChanged(path.join(build, "css", "base.css"), `${helmet.style.trim()}\n${FULL_PAGE_CSS}`);
  writeIfChanged(path.join(build, "chrome", "font-links.njk"), fontLinkPartial(helmet.links));
  writeIfChanged(
    path.join(build, "meta.json"),
    `${JSON.stringify({ title: helmet.title, description: helmet.description, views: bundle.views }, null, 2)}\n`,
  );
  return { views: bundle.views, assets: bundle.assets.map(({ key, src, mime }) => ({ key, src, mime })) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = extractProject();
  console.log(`Extracted ${result.views.length} view(s): ${result.views.join(", ")}`);
  console.log(`Wrote ${result.assets.length} asset(s).`);
}
